package export

import (
	"fmt"
	"html/template"
	"strings"
	"time"

	"github.com/amitgupta1000/WebSearch_GO/internal/models"
)

func newsReportTitle(report *models.NewsReport) string {
	return nonEmpty(report.Query, "News") + " — News Report"
}

func deepSearchReportTitle(report *models.DeepSearchReport) string {
	return nonEmpty(report.Question, "Deep Search") + " — Deep Search Report"
}

func renderNewsMarkdown(report *models.NewsReport) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n\n_%s · generated %s_\n\n", newsReportTitle(report), BrandName, generatedStamp(report.CompletedAt))
	fmt.Fprintf(&b, "**Query:** %s\n\n## Summary\n\n%s\n\n", report.Query, report.Synthesis.Summary)
	if report.Synthesis.Headline != "" {
		fmt.Fprintf(&b, "**Headline:** %s\n\n", report.Synthesis.Headline)
	}
	writeStringList(&b, "Key developments", report.Synthesis.KeyDevelopments)
	if len(report.Synthesis.Citations) > 0 {
		b.WriteString("## Citations\n\n")
		for _, citation := range report.Synthesis.Citations {
			fmt.Fprintf(&b, "- %s: %s\n", citation.Claim, strings.Join(citation.URLs, ", "))
		}
		b.WriteString("\n")
	}
	if report.Synthesis.Article != "" {
		fmt.Fprintf(&b, "## Report\n\n%s\n\n", report.Synthesis.Article)
	}
	fmt.Fprintf(&b, "## Run metrics\n\n- Queries: %d\n- Articles selected: %d\n- Articles scraped: %d\n- Chunks collected: %d\n",
		report.QueriesUsed, report.ArticlesSelected, report.ArticlesScraped, report.ChunksCollected)
	return b.String()
}

func renderDeepSearchMarkdown(report *models.DeepSearchReport) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n\n_%s · generated %s_\n\n", deepSearchReportTitle(report), BrandName, generatedStamp(report.CompletedAt))
	fmt.Fprintf(&b, "**Question:** %s\n\n## Summary\n\n%s\n\n", report.Question, report.Synthesis.Summary)
	if report.Synthesis.Report != "" {
		fmt.Fprintf(&b, "## Report\n\n%s\n\n", report.Synthesis.Report)
	}
	for _, finding := range report.Synthesis.Findings {
		fmt.Fprintf(&b, "- **%s** — %s\n", finding.Statement, strings.Join(finding.URLs, ", "))
	}
	writeStringList(&b, "Open questions", report.Synthesis.OpenQuestions)
	fmt.Fprintf(&b, "\n## Run metrics\n\n- Queries: %d\n- Search hits: %d\n- Pages scraped: %d\n- Rounds: %d\n",
		report.QueriesUsed, report.SearchHits, report.PagesScraped, report.RoundsRun)
	return b.String()
}

func writeStringList(b *strings.Builder, title string, values []string) {
	if len(values) == 0 {
		return
	}
	fmt.Fprintf(b, "## %s\n\n", title)
	for _, value := range values {
		fmt.Fprintf(b, "- %s\n", value)
	}
	b.WriteString("\n")
}

func renderNewsHTML(report *models.NewsReport) string {
	return renderResearchHTML(newsReportTitle(report), nonEmpty(report.Query, "News report"), renderNewsMarkdown(report))
}

func renderDeepSearchHTML(report *models.DeepSearchReport) string {
	return renderResearchHTML(deepSearchReportTitle(report), nonEmpty(report.Question, "Deep search report"), renderDeepSearchMarkdown(report))
}

func renderResearchHTML(title, subject, markdown string) string {
	body := "<pre class=\"report-text\">" + template.HTMLEscapeString(markdown) + "</pre>"
	return executeDocument(researchHTMLTemplate, document{
		Title:        title,
		CoverSubject: subject,
		Kicker:       "Research Report",
		CoverSummary: "Evidence-backed report generated by " + BrandName + ".",
		GeneratedAt:  generatedStamp(time.Now().UTC()),
		Body:         template.HTML(body),
	})
}

var researchHTMLTemplate = documentTemplate("research", `
<header><h1>{{.Title}}</h1><p class="subtitle">{{.CoverSubject}}</p></header>
{{.Body}}
`)
