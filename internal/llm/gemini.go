package llm

import (
	"context"
	"encoding/json"
	"fmt"
	"os"

	"google.golang.org/genai"
)

// GeminiClient wraps the Google GenAI SDK for Gemini 2.5 Flash Lite.
type GeminiClient struct {
	client *genai.Client
	model  string
}

// NewGeminiClient initializes a client with Vertex AI / Google GenAI authentication.
func NewGeminiClient(ctx context.Context, model string) (*GeminiClient, error) {
	if model == "" {
		model = "gemini-2.5-flash-lite"
	}

	// The SDK picks up GOOGLE_API_KEY or Application Default Credentials automatically
	client, err := genai.NewClient(ctx, nil)
	if err != nil {
		// If standard init fails without explicit key, attempt with backend config
		client, err = genai.NewClient(ctx, &genai.ClientConfig{
			Project:  os.Getenv("GOOGLE_CLOUD_PROJECT"),
			Location: os.Getenv("GCP_REGION"),
		})
		if err != nil {
			return nil, fmt.Errorf("failed to initialize GenAI client: %w", err)
		}
	}

	return &GeminiClient{
		client: client,
		model:  model,
	}, nil
}

// GenerateContent sends prompt messages to Gemini and returns text.
func (g *GeminiClient) GenerateContent(ctx context.Context, systemPrompt, userPrompt string) (string, error) {
	config := &genai.GenerateContentConfig{
		SystemInstruction: &genai.Content{
			Parts: []*genai.Part{
				{Text: systemPrompt},
			},
		},
		Temperature: genai.Ptr(float32(0.2)),
	}

	resp, err := g.client.Models.GenerateContent(ctx, g.model, genai.Text(userPrompt), config)
	if err != nil {
		return "", fmt.Errorf("gemini generation failed: %w", err)
	}

	if len(resp.Candidates) == 0 || resp.Candidates[0].Content == nil {
		return "", fmt.Errorf("no content generated by gemini")
	}

	var output string
	for _, part := range resp.Candidates[0].Content.Parts {
		output += part.Text
	}

	return output, nil
}

// GenerateStructured formats the prompt and unmarshals JSON response into target interface.
func (g *GeminiClient) GenerateStructured(ctx context.Context, systemPrompt, userPrompt string, target any) error {
	sysInstruction := systemPrompt + "\n\nCRITICAL: Respond ONLY with valid JSON matching the requested schema. Do not enclose in markdown blocks unless unavoidable, and do not add explanatory preamble."

	rawJSON, err := g.GenerateContent(ctx, sysInstruction, userPrompt)
	if err != nil {
		return err
	}

	// Clean accidental ```json codeblock markers if present
	cleaned := cleanJSONString(rawJSON)

	if err := json.Unmarshal([]byte(cleaned), target); err != nil {
		return fmt.Errorf("failed to unmarshal structured output: %w (raw: %s)", err, cleaned)
	}

	return nil
}

func cleanJSONString(s string) string {
	if len(s) >= 7 && s[:7] == "```json" {
		s = s[7:]
	} else if len(s) >= 3 && s[:3] == "```" {
		s = s[3:]
	}
	if len(s) >= 3 && s[len(s)-3:] == "```" {
		s = s[:len(s)-3]
	}
	return s
}
